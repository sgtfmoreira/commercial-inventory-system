const { Router } = require('express');
const auth = require('../middlewares/authMiddleware');
const requireCapability = require('../middlewares/requireCapability');
const validate = require('../middlewares/validate');
const validateParams = require('../middlewares/validateParams');
const validateQuery = require('../middlewares/validateQuery');
const controller = require('../controllers/checklistTemplateController');
const runController = require('../controllers/checklistRunController');
const schemas = require('../validations/checklistTemplateApiValidation');
const runSchemas = require('../validations/checklistRunValidation');
const evidenceUpload = require('../middlewares/checklistEvidenceUpload');

const router = Router();
const canManage = requireCapability('checklists.templates.manage', { legacyRoles: ['ADMIN'] });
const canManageRuns = requireCapability('checklists.runs.manage', { legacyRoles: ['ADMIN', 'MANAGER'] });
const canExecute = requireCapability('checklists.execute', { legacyRoles: ['ADMIN', 'MANAGER', 'STAFF', 'STOCK_COUNTER'] });
const canApprove = requireCapability('checklists.approve', { legacyRoles: ['ADMIN', 'MANAGER'] });

router.use(auth);
router.get('/capabilities', runController.capabilities);
router.get('/my-runs', canExecute, runController.listMine);
router.post('/runs/:runId/start', validateParams(runSchemas.runIdParamSchema), canExecute, runController.start);
router.get('/attempts/:attemptId', validateParams(runSchemas.attemptIdParamSchema), canExecute, runController.getAttempt);
router.put('/attempts/:attemptId/responses/:itemId', validateParams(runSchemas.responseParamsSchema), canExecute, validate(runSchemas.saveResponseSchema), runController.saveResponse);
router.post('/responses/:responseId/evidences', validateParams(runSchemas.responseIdParamSchema), canExecute, evidenceUpload.single('evidence'), runController.addEvidence);
router.get('/evidences/:evidenceId/content', validateParams(runSchemas.evidenceIdParamSchema), canExecute, runController.evidenceContent);
router.post('/attempts/:attemptId/submit', validateParams(runSchemas.attemptIdParamSchema), canExecute, validate(runSchemas.submitAttemptSchema), runController.submit);
router.get('/approvals', canApprove, runController.pendingApprovals);
router.get('/approval-attempts/:attemptId', validateParams(runSchemas.attemptIdParamSchema), canApprove, runController.approvalAttempt);
router.post('/attempts/:attemptId/approve', validateParams(runSchemas.attemptIdParamSchema), canApprove, validate(runSchemas.approveAttemptSchema), runController.approve);
router.post('/attempts/:attemptId/reject', validateParams(runSchemas.attemptIdParamSchema), canApprove, validate(runSchemas.rejectAttemptSchema), runController.reject);
router.get('/approval-evidences/:evidenceId/content', validateParams(runSchemas.evidenceIdParamSchema), canApprove, runController.approvalEvidenceContent);
router.get('/runs/:runId/history', validateParams(runSchemas.runIdParamSchema), canApprove, runController.history);
router.get('/reports', canApprove, validateQuery(runSchemas.reportQuerySchema), runController.report);
router.get('/published-templates', canManageRuns, runController.publishedTemplates);
router.get('/eligible-assignees', canManageRuns, runController.eligibleAssignees);
router.get('/runs', canManageRuns, runController.list);
router.post('/runs', canManageRuns, validate(runSchemas.createRunSchema), runController.create);
router.get('/runs/:runId', validateParams(runSchemas.runIdParamSchema), canManageRuns, runController.get);
router.patch('/runs/:runId/assignment', validateParams(runSchemas.runIdParamSchema), canManageRuns, validate(runSchemas.reassignRunSchema), runController.reassign);
router.get('/templates', canManage, controller.list);
router.post('/templates', canManage, validate(schemas.createTemplateSchema), controller.create);
router.get('/templates/:templateId', validateParams(schemas.templateIdParamSchema), canManage, controller.get);
router.put('/templates/:templateId/draft', validateParams(schemas.templateIdParamSchema), canManage, validate(schemas.saveDraftSchema), controller.saveDraft);
router.post('/templates/:templateId/publish', validateParams(schemas.templateIdParamSchema), canManage, validate(schemas.expectedVersionSchema), controller.publish);
router.post('/templates/:templateId/versions', validateParams(schemas.templateIdParamSchema), canManage, validate(schemas.cloneVersionSchema), controller.cloneVersion);
router.post('/templates/:templateId/versions/:versionId/retire', validateParams(schemas.versionParamsSchema), canManage, validate(schemas.expectedVersionSchema), controller.retire);

module.exports = router;
